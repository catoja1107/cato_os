#!/usr/bin/env python3
"""Converts the splash PNG into a cropped grayscale image embedded in the loader.

Usage: mksplash.py <input.png> <output.c> <output.pgm>

The C file is compiled into BOOTX64.EFI. The PGM holds the same pixels and is
the reference image for the QEMU smoke test.
"""
import os
import struct
import sys
import zlib

# The source is portrait, so keep the band containing the face and whiskers.
CROP_X = 0
CROP_Y = 390
CROP_WIDTH = 700
CROP_HEIGHT = 600

# Values at or below this are compression noise in the black background.
BLACK_LEVEL = 6
# Width in pixels of the fade to black at each crop edge.
FEATHER = 36


def read_png(path):
    """Decodes an 8-bit, non-interlaced PNG using only the standard library."""
    with open(path, "rb") as file:
        data = file.read()
    if data[:8] != b"\x89PNG\r\n\x1a\n":
        raise ValueError(f"{path} is not a PNG")

    position = 8
    compressed = []
    header = None
    while position < len(data):
        length, kind = struct.unpack(">I4s", data[position:position + 8])
        body = data[position + 8:position + 8 + length]
        if kind == b"IHDR":
            header = struct.unpack(">IIBBBBB", body)
        elif kind == b"IDAT":
            compressed.append(body)
        position += 12 + length

    if header is None:
        raise ValueError(f"{path} has no IHDR chunk")
    width, height, depth, color, _, _, interlace = header
    channels = {0: 1, 2: 3, 4: 2, 6: 4}.get(color)
    if depth != 8 or channels is None or interlace:
        raise ValueError(f"{path}: only 8-bit non-interlaced gray or RGB PNGs are supported")

    raw = zlib.decompress(b"".join(compressed))
    stride = width * channels
    previous = bytearray(stride)
    rows = []
    offset = 0
    for _ in range(height):
        filter_type = raw[offset]
        line = bytearray(raw[offset + 1:offset + 1 + stride])
        offset += stride + 1
        unfilter(line, previous, filter_type, channels)
        rows.append(line)
        previous = line
    return width, height, channels, rows


def unfilter(line, previous, filter_type, channels):
    """Reverses a PNG scanline filter (PNG Specification, section 9)."""
    if filter_type == 0:
        return
    if filter_type > 4:
        raise ValueError(f"invalid PNG filter {filter_type}")

    for i in range(len(line)):
        left = line[i - channels] if i >= channels else 0
        up = previous[i]
        corner = previous[i - channels] if i >= channels else 0
        if filter_type == 1:
            predicted = left
        elif filter_type == 2:
            predicted = up
        elif filter_type == 3:
            predicted = (left + up) // 2
        else:
            estimate = left + up - corner
            distances = (abs(estimate - left), abs(estimate - up), abs(estimate - corner))
            predicted = (left, up, corner)[distances.index(min(distances))]
        line[i] = (line[i] + predicted) & 0xff


def luma(pixel, channels):
    if channels < 3:
        return pixel[0]
    return (pixel[0] * 77 + pixel[1] * 150 + pixel[2] * 29) >> 8


def edge_fade(x, y):
    distance = min(x, CROP_WIDTH - 1 - x, y, CROP_HEIGHT - 1 - y)
    if distance >= FEATHER:
        return 1.0
    t = (distance + 0.5) / FEATHER
    return t * t * (3 - 2 * t)


def build_splash(width, height, channels, rows):
    if CROP_X + CROP_WIDTH > width or CROP_Y + CROP_HEIGHT > height:
        raise ValueError(f"crop does not fit a {width}x{height} image")

    output = bytearray(CROP_WIDTH * CROP_HEIGHT)
    scale = 255 / (255 - BLACK_LEVEL)
    for y in range(CROP_HEIGHT):
        row = rows[CROP_Y + y]
        for x in range(CROP_WIDTH):
            start = (CROP_X + x) * channels
            value = max(luma(row[start:start + channels], channels) - BLACK_LEVEL, 0)
            output[y * CROP_WIDTH + x] = min(255, int(value * scale * edge_fade(x, y) + 0.5))
    return output


def write_atomic(path, data):
    temporary = f"{path}.tmp"
    with open(temporary, "wb") as file:
        file.write(data)
    os.replace(temporary, path)


def c_source(pixels):
    lines = [
        "/* Generated by scripts/mksplash.py. Do not edit. */",
        "#include <stdint.h>",
        "",
        f"const uint32_t splash_width = {CROP_WIDTH};",
        f"const uint32_t splash_height = {CROP_HEIGHT};",
        f"const uint8_t splash_pixels[{len(pixels)}] = {{",
    ]
    for start in range(0, len(pixels), 32):
        lines.append(",".join(str(value) for value in pixels[start:start + 32]) + ",")
    lines.extend(["};", ""])
    return "\n".join(lines).encode()


def main():
    if len(sys.argv) != 4:
        print(__doc__, file=sys.stderr)
        return 2

    input_path, c_path, pgm_path = sys.argv[1:]
    pixels = build_splash(*read_png(input_path))
    write_atomic(pgm_path, f"P5\n{CROP_WIDTH} {CROP_HEIGHT}\n255\n".encode() + bytes(pixels))
    write_atomic(c_path, c_source(pixels))
    return 0


if __name__ == "__main__":
    sys.exit(main())
